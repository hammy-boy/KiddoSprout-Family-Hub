import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const outputUrl = new URL("../_______/wisp/frontend/vendor/supabase-js-2.116.0.js", import.meta.url);
const outputFile = fileURLToPath(outputUrl);
const projectDirectory = fileURLToPath(new URL("../", import.meta.url));

await mkdir(dirname(outputFile), { recursive: true });
await build({
  entryPoints: ["@supabase/supabase-js"],
  absWorkingDir: projectDirectory,
  outfile: outputFile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
  sourcemap: false,
  logLevel: "info",
});

const bundledSource = await readFile(outputFile, "utf8");
await writeFile(
  outputFile,
  `/* @supabase/supabase-js 2.116.0 — generated by scripts/build-wisp-client.mjs */\n${bundledSource.replace(/[ \t]+$/gm, "")}`,
  "utf8",
);
