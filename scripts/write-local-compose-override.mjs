import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { assessLocalEmailReadiness, isBrowserSafeSupabaseKey } from "./email-readiness.mjs";

const requiredNames = [
  "SUPABASE_URL",
  "SUPABASE_PUBLISHABLE_KEY",
  "TURNSTILE_SITE_KEY"
];

for (const name of requiredNames) {
  if (!process.env[name]?.trim()) {
    throw new Error(`Cannot save local Docker settings: ${name} is missing.`);
  }
}

if (!isBrowserSafeSupabaseKey(process.env.SUPABASE_PUBLISHABLE_KEY)) {
  throw new Error("Cannot save local Docker settings: SUPABASE_PUBLISHABLE_KEY is not browser-safe.");
}

const yamlString = (value) => JSON.stringify(String(value));
const overrideUrl = new URL("../docker-compose.override.yml", import.meta.url);
const browserConfigUrl = new URL("../supabase-config.js", import.meta.url);
const envUrl = new URL("../.env", import.meta.url);

function readDotEnv() {
  if (!existsSync(envUrl)) return {};
  const values = {};
  for (const sourceLine of readFileSync(envUrl, "utf8").split(/\r?\n/)) {
    const line = sourceLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    } else {
      value = value.replace(/\s+#.*$/, "").trim();
    }
    values[match[1]] = value;
  }
  return values;
}

const dotEnv = readDotEnv();
if (existsSync(envUrl)) chmodSync(envUrl, 0o600);
const localValue = (name) => process.env[name]?.trim() || dotEnv[name]?.trim() || "";
const hasPlaidClientId = Boolean(localValue("PLAID_CLIENT_ID"));
const hasPlaidSecret = Boolean(localValue("PLAID_SECRET"));
const bankTokenEncryptionKey = localValue("BANK_TOKEN_ENCRYPTION_KEY");
const smtpNames = ["SMTP_HOST", "SMTP_PORT", "SMTP_USER", "SMTP_PASS", "SMTP_FROM"];
const smtpValues = smtpNames.map(localValue);
const smtpReady = smtpValues.every(Boolean);
const smtpConfigured = ["SMTP_HOST", "SMTP_USER", "SMTP_PASS", "SMTP_FROM"].some((name) => Boolean(localValue(name)));
const googleOauthNames = ["GOOGLE_OAUTH_CLIENT_ID", "GOOGLE_OAUTH_CLIENT_SECRET"];
const googleOauthValues = googleOauthNames.map(localValue);
const googleAuthReady = googleOauthValues.every(Boolean);

if (googleOauthValues.some(Boolean) && !googleAuthReady) {
  throw new Error("GOOGLE_OAUTH_CLIENT_ID and GOOGLE_OAUTH_CLIENT_SECRET must either both be set or both be empty.");
}
if (smtpConfigured) {
  const emailReadiness = assessLocalEmailReadiness(Object.fromEntries(smtpNames.map((name) => [name, localValue(name)])));
  if (!emailReadiness.ready) {
    throw new Error(emailReadiness.errors.join(" "));
  }
}
if (!smtpReady && !googleAuthReady) {
  throw new Error("Configure either Google OAuth or external SMTP before starting KiddoSprout.");
}

if (hasPlaidClientId !== hasPlaidSecret) {
  throw new Error("PLAID_CLIENT_ID and PLAID_SECRET must either both be set or both be empty.");
}
if (hasPlaidClientId && !bankTokenEncryptionKey) {
  throw new Error("BANK_TOKEN_ENCRYPTION_KEY is required when Plaid credentials are set.");
}
if (bankTokenEncryptionKey
    && !/^(?:[0-9a-fA-F]{64}|[A-Za-z0-9+/]{43}=|[A-Za-z0-9_-]{43})$/.test(bankTokenEncryptionKey)) {
  throw new Error("BANK_TOKEN_ENCRYPTION_KEY must be 32-byte base64 or 64-character hexadecimal.");
}

const requestedDemoMode = localValue("BANK_DEMO_MODE").toLowerCase();
if (requestedDemoMode && !["true", "false"].includes(requestedDemoMode)) {
  throw new Error("BANK_DEMO_MODE must be true or false.");
}

// `npm run dev` is deliberately useful without a financial-services account:
// no Plaid credentials means an isolated pretend-bank connection with no real data.
// The base Compose file defaults this to false for deployed/public environments.
const bankDemoMode = hasPlaidClientId ? (requestedDemoMode || "false") : "true";
const contents = `# Generated by npm run dev. Do not commit this file.
# Docker Compose loads it automatically, including when started from Docker Desktop.
services:
  kiddosprout:
    environment:
      SUPABASE_URL: ${yamlString(process.env.SUPABASE_URL)}
      SUPABASE_PUBLISHABLE_KEY: ${yamlString(process.env.SUPABASE_PUBLISHABLE_KEY)}
      TURNSTILE_SITE_KEY: ${yamlString(process.env.TURNSTILE_SITE_KEY)}
      AUTH_EMAIL_DELIVERY_READY: ${yamlString(process.env.AUTH_EMAIL_DELIVERY_READY === "true" && smtpReady ? "true" : "false")}
      GOOGLE_AUTH_READY: ${yamlString(googleAuthReady ? "true" : "false")}

  voice-api:
    environment:
      SUPABASE_URL: ${yamlString(process.env.SUPABASE_URL)}
      SUPABASE_PUBLISHABLE_KEY: ${yamlString(process.env.SUPABASE_PUBLISHABLE_KEY)}

  blocker-api:
    environment:
      SUPABASE_URL: ${yamlString(process.env.SUPABASE_URL)}
      SUPABASE_PUBLISHABLE_KEY: ${yamlString(process.env.SUPABASE_PUBLISHABLE_KEY)}

  bank-api:
    environment:
      SUPABASE_URL: ${yamlString(process.env.SUPABASE_URL)}
      SUPABASE_PUBLISHABLE_KEY: ${yamlString(process.env.SUPABASE_PUBLISHABLE_KEY)}
      BANK_DEMO_MODE: ${yamlString(bankDemoMode)}
`;

writeFileSync(overrideUrl, contents, { encoding: "utf8", mode: 0o600 });
chmodSync(overrideUrl, 0o600);

const browserConfig = `// Generated by npm run dev. Do not commit this file.
window.KIDDO_SPROUT_SUPABASE = {
  publicDemoOnly: false,
  url: ${yamlString(process.env.SUPABASE_URL)},
  publishableKey: ${yamlString(process.env.SUPABASE_PUBLISHABLE_KEY)},
  turnstileSiteKey: ${yamlString(process.env.TURNSTILE_SITE_KEY)},
  emailDeliveryReady: ${process.env.AUTH_EMAIL_DELIVERY_READY === "true" && smtpReady ? "true" : "false"},
  googleAuthReady: ${googleAuthReady ? "true" : "false"}
};
`;

writeFileSync(browserConfigUrl, browserConfig, { encoding: "utf8", mode: 0o644 });
chmodSync(browserConfigUrl, 0o644);

console.log(hasPlaidClientId && bankDemoMode === "false"
  ? "Smart Spending bank: Plaid mode (credentials stay in bank-api)."
  : "Smart Spending bank: safe local demo mode (no real bank data)."
);
